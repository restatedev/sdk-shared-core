impl TunnelEngineOptions {
    /// Resolve the options against the process environment. Every input is validated here,
    /// including an initial read of a token file.
    pub fn resolve(options: ConnectOptions) -> Result<Self, ConfigError> {
        Self::resolve_with_env(options, |name| match std::env::var(name) {
            Ok(value) => Ok(Some(value)),
            Err(std::env::VarError::NotPresent) => Ok(None),
            Err(std::env::VarError::NotUnicode(_)) => Err(ConfigError::NonUnicodeEnvironment(
                // Only the names below are ever read; keep the static name for the message.
                KNOWN_ENVS
                    .iter()
                    .copied()
                    .find(|known| *known == name)
                    .unwrap_or("environment variable"),
            )),
        })
    }

    /// Like [`resolve`](Self::resolve), with an explicit environment (for tests and hosts
    /// that do not use the process environment).
    pub fn resolve_with_env(
        options: ConnectOptions,
        env: impl Fn(&str) -> Result<Option<String>, ConfigError>,
    ) -> Result<Self, ConfigError> {
        let env = |name: &str| -> Result<Option<String>, ConfigError> {
            Ok(env(name)?.filter(|value| !value.is_empty()))
        };

        let name = match nonempty(options.name.as_deref()) {
            Some(name) => name.to_owned(),
            None => match env(CONNECT_NAME_ENV)? {
                Some(name) => name,
                None => env(INPROC_TUNNEL_NAME_ENV)?.ok_or(ConfigError::MissingName)?,
            },
        };
        if !valid_name(&name) {
            return Err(ConfigError::InvalidName(name));
        }

        let coordinates = resolve_coordinates(options.key.as_deref(), options.token, &env)?;

        let discovery = match options.servers {
            Some(Servers::Srv(srv)) => {
                validate_srv_name(&srv)?;
                Discovery::Srv(srv)
            }
            Some(Servers::Explicit(servers)) => {
                if servers.is_empty() {
                    return Err(ConfigError::Servers("the server list is empty".into()));
                }
                Discovery::Explicit(
                    servers
                        .iter()
                        .map(|server| parse_server_address(server))
                        .collect::<Result<Vec<_>, _>>()?,
                )
            }
            None => Discovery::Srv(srv_name_for_region_domain(&coordinates.region)),
        };

        let worker_id = match nonempty(options.worker_id.as_deref()) {
            Some(worker_id) => {
                if !header_safe(worker_id) {
                    return Err(ConfigError::InvalidHeaderValue("worker_id"));
                }
                Some(worker_id.to_owned())
            }
            None => None,
        };

        // Fail token misconfiguration now. Every dial calls the same method again and
        // therefore observes Secret rotation.
        coordinates.auth_token.bearer()?;

        Ok(Self {
            name,
            environment_id: coordinates.environment_id,
            region: coordinates.region,
            source: coordinates.source,
            worker_id,
            discovery,
            signing_public_key: coordinates.signing_public_key,
            tuning: options.tuning,
            auth_token: coordinates.auth_token,
        })
    }

    /// The registration identifier the CLI and the Cloud UI accept.
    pub fn registration_identifier(&self) -> String {
        format!("connect://{}", self.name)
    }

    /// The Cloud UI deep link that opens the register dialog pre-filled.
    pub fn registration_deep_link(&self) -> String {
        format!(
            "{}/to/overview?register-deployment=connect://{}",
            crate::cloud_keys::CLOUD_UI_URL,
            self.name
        )
    }

    /// The `Authorization` value for the next dial (re-reads a token file).
    pub(crate) fn bearer(&self) -> Result<String, TokenError> {
        self.auth_token.bearer()
    }
}

const KNOWN_ENVS: &[&str] = &[
    CONNECT_NAME_ENV,
    CONNECT_KEY_ENV,
    INPROC_TUNNEL_NAME_ENV,
    INPROC_ENVIRONMENT_ID_ENV,
    INPROC_CLOUD_REGION_ENV,
    INPROC_SIGNING_PUBLIC_KEY_ENV,
    INPROC_AUTH_TOKEN_FILE_ENV,
    AUTH_TOKEN_ENV,
];

struct Coordinates {
    environment_id: String,
    region: String,
    signing_public_key: String,
    auth_token: AuthToken,
    source: ConfigSource,
}

fn resolve_coordinates(
    key_option: Option<&str>,
    token_option: Option<Token>,
    env: &impl Fn(&str) -> Result<Option<String>, ConfigError>,
) -> Result<Coordinates, ConfigError> {
    let token_option = match token_option {
        Some(Token::Literal(token)) if !token.is_empty() => {
            if !header_safe(&token) {
                return Err(ConfigError::InvalidHeaderValue("token"));
            }
            Some(AuthToken::Literal(Arc::from(token.as_str())))
        }
        Some(Token::File(path)) if !path.as_os_str().is_empty() => {
            Some(AuthToken::File(Arc::new(path)))
        }
        _ => None,
    };
    let resolve_token = |what: &'static str| -> Result<AuthToken, ConfigError> {
        match &token_option {
            Some(token) => Ok(token.clone()),
            None => token_from_env(env)?.ok_or(ConfigError::MissingToken { what }),
        }
    };
    let (key, source, what) = match nonempty(key_option) {
        Some(key) => (Some(key.to_owned()), ConfigSource::Code, "the key option"),
        None => (
            env(CONNECT_KEY_ENV)?,
            ConfigSource::ConnectKey,
            CONNECT_KEY_ENV,
        ),
    };

    if let Some(key) = key {
        let key = ConnectKey::parse(&key).map_err(|error| ConfigError::Key { what, error })?;
        // A key for one environment next to an operator's variables for another is almost
        // certainly a stray developer key: say so.
        if let Some(injected) = env(INPROC_ENVIRONMENT_ID_ENV)? {
            if injected != key.environment_id {
                tracing::warn!(
                    "The connect key is for environment {} but {INPROC_ENVIRONMENT_ID_ENV} is set to {injected}; the key wins",
                    key.environment_id
                );
            }
        }
        let auth_token = match key.api_key {
            Some(api_key) => AuthToken::Literal(Arc::from(api_key.as_str())),
            None => resolve_token(what)?,
        };
        return Ok(Coordinates {
            environment_id: key.environment_id,
            region: key.region,
            signing_public_key: key.signing_public_key,
            auth_token,
            source,
        });
    }

    // The operator set. Without even an environment id, there is no configuration at all.
    let environment_id = env(INPROC_ENVIRONMENT_ID_ENV)?.ok_or(ConfigError::MissingKey)?;
    validate_environment_id(&environment_id).map_err(|_| ConfigError::InvalidOperatorConfig {
        var: INPROC_ENVIRONMENT_ID_ENV,
        reason: "expected env_ followed by letters, digits, '_' or '-'",
    })?;
    let region = env(INPROC_CLOUD_REGION_ENV)?.ok_or(ConfigError::IncompleteOperatorConfig(
        INPROC_CLOUD_REGION_ENV,
    ))?;
    validate_region_domain(&region).map_err(|_| ConfigError::InvalidOperatorConfig {
        var: INPROC_CLOUD_REGION_ENV,
        reason: "expected lowercase labels of letters, digits or '-' (for example eu, us or <slug>.byoc)",
    })?;
    let region = format!("{region}.{CLOUD_DOMAIN}");
    let signing_public_key = env(INPROC_SIGNING_PUBLIC_KEY_ENV)?.ok_or(
        ConfigError::IncompleteOperatorConfig(INPROC_SIGNING_PUBLIC_KEY_ENV),
    )?;
    validate_signing_public_key(&signing_public_key).map_err(|_| {
        ConfigError::InvalidOperatorConfig {
            var: INPROC_SIGNING_PUBLIC_KEY_ENV,
            reason: "expected a request-identity public key (publickeyv1_...)",
        }
    })?;
    let auth_token = resolve_token(INPROC_ENVIRONMENT_ID_ENV).map_err(|error| match error {
        ConfigError::MissingToken { .. } => ConfigError::IncompleteOperatorConfig(AUTH_TOKEN_ENV),
        other => other,
    })?;
    Ok(Coordinates {
        environment_id,
        region,
        signing_public_key,
        auth_token,
        source: ConfigSource::Operator,
    })
}

/// `RESTATE_AUTH_TOKEN`, then the file named by `RESTATE_INPROC_AUTH_TOKEN_FILE`.
fn token_from_env(
    env: &impl Fn(&str) -> Result<Option<String>, ConfigError>,
) -> Result<Option<AuthToken>, ConfigError> {
    if let Some(token) = env(AUTH_TOKEN_ENV)? {
        if !header_safe(&token) {
            return Err(ConfigError::InvalidHeaderValue(AUTH_TOKEN_ENV));
        }
        return Ok(Some(AuthToken::Literal(Arc::from(token.as_str()))));
    }
    Ok(env(INPROC_AUTH_TOKEN_FILE_ENV)?.map(|path| AuthToken::File(Arc::new(PathBuf::from(path)))))
}

/// A process-stable token source. File-backed sources reopen the path on every call so
/// Kubernetes projected-Secret symlink swaps are observed.
#[derive(Clone)]
pub(crate) enum AuthToken {
    Literal(Arc<str>),
    File(Arc<PathBuf>),
}

impl AuthToken {
    /// Read the current token and build the `Authorization` value. The token itself has no
    /// `Display` or `Debug` representation in this module.
    pub(crate) fn bearer(&self) -> Result<String, TokenError> {
        match self {
            Self::Literal(token) => Ok(format!("Bearer {token}")),
            Self::File(path) => Ok(format!("Bearer {}", read_token_file(path)?)),
        }
    }
}

impl fmt::Debug for AuthToken {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Literal(_) => f.debug_tuple("Literal").field(&Redacted).finish(),
            Self::File(path) => f.debug_tuple("File").field(path).finish(),
        }
    }
}

fn read_token_file(path: &Path) -> Result<String, TokenError> {
    // `metadata` follows symlinks, which is required for Kubernetes projected Secrets.
    // Checking before open avoids blocking on a configured FIFO.
    let metadata = std::fs::metadata(path).map_err(|source| TokenError::Metadata {
        path: path.to_owned(),
        source,
    })?;
    if !metadata.is_file() {
        return Err(TokenError::NotRegularFile(path.to_owned()));
    }
    if metadata.len() > MAX_AUTH_TOKEN_FILE_BYTES {
        return Err(TokenError::TooLarge {
            path: path.to_owned(),
            size: metadata.len(),
        });
    }

    let file = File::open(path).map_err(|source| TokenError::Open {
        path: path.to_owned(),
        source,
    })?;
    let opened_metadata = file.metadata().map_err(|source| TokenError::Metadata {
        path: path.to_owned(),
        source,
    })?;
    if !opened_metadata.is_file() {
        return Err(TokenError::NotRegularFile(path.to_owned()));
    }

    // Bound the actual read as well as metadata. This catches files that grow between stat
    // and read, and prevents an unbounded read after path races.
    let mut bytes =
        Vec::with_capacity(opened_metadata.len().min(MAX_AUTH_TOKEN_FILE_BYTES) as usize);
    file.take(MAX_AUTH_TOKEN_FILE_BYTES + 1)
        .read_to_end(&mut bytes)
        .map_err(|source| TokenError::Read {
            path: path.to_owned(),
            source,
        })?;
    if bytes.len() as u64 > MAX_AUTH_TOKEN_FILE_BYTES {
        return Err(TokenError::TooLarge {
            path: path.to_owned(),
            size: bytes.len() as u64,
        });
    }

    let token = String::from_utf8(bytes).map_err(|_| TokenError::InvalidUtf8(path.to_owned()))?;
    // Trimmed because mounted secrets routinely carry a trailing newline.
    let token = token.trim();
    if token.is_empty() {
        return Err(TokenError::Empty(path.to_owned()));
    }
    if !header_safe(token) {
        return Err(TokenError::InvalidHeader(path.to_owned()));
    }
    Ok(token.to_owned())
}

fn nonempty(value: Option<&str>) -> Option<&str> {
    value.filter(|value| !value.is_empty())
}

fn valid_name(value: &str) -> bool {
    !value.is_empty()
        && value
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'_' | b'-'))
}

fn validate_srv_name(name: &str) -> Result<(), ConfigError> {
    let valid = !name.is_empty()
        && name
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'_' | b'-'));
    if valid {
        Ok(())
    } else {
        Err(ConfigError::Servers(format!("invalid SRV name {name:?}")))
    }
}

/// Parse an explicit `host:port`, `https://host[:port]`, or `http://host[:port]` tunnel server.
pub fn parse_server_address(address: &str) -> Result<ServerAddress, ConfigError> {
    let invalid = |reason: &str| ConfigError::Servers(format!("{reason}: {address:?}"));

    let (plaintext, authority, default_port) = match address.find("://") {
        Some(index) => {
            let (scheme, rest) = (&address[..index], &address[index + 3..]);
            let plaintext = match scheme {
                "http" => true,
                "https" => false,
                _ => {
                    return Err(invalid(
                        "unsupported tunnel server scheme (use http or https)",
                    ))
                }
            };
            let authority = rest.strip_suffix('/').unwrap_or(rest);
            if authority.contains(['/', '?', '#']) {
                return Err(invalid(
                    "tunnel server URL must not have a path, query, or fragment",
                ));
            }
            if authority.contains('@') {
                return Err(invalid(
                    "tunnel server URL must not contain user information",
                ));
            }
            (plaintext, authority, Some(if plaintext { 80 } else { 443 }))
        }
        None => (false, address, None),
    };

    let (host, port) = if let Some(rest) = authority.strip_prefix('[') {
        let end = rest
            .find(']')
            .ok_or_else(|| invalid("invalid tunnel server address"))?;
        let host = &rest[..end];
        let port = match &rest[end + 1..] {
            "" => None,
            tail => Some(
                tail.strip_prefix(':')
                    .ok_or_else(|| invalid("invalid tunnel server address"))?,
            ),
        };
        (host, port)
    } else {
        match authority.rfind(':') {
            Some(index) if !authority[..index].contains(':') => {
                (&authority[..index], Some(&authority[index + 1..]))
            }
            Some(_) => return Err(invalid("IPv6 tunnel server addresses must be bracketed")),
            None => (authority, None),
        }
    };

    if host.is_empty() {
        return Err(invalid("tunnel server address is missing a host"));
    }
    if !host
        .bytes()
        .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'-' | b'_' | b':'))
    {
        return Err(invalid("invalid tunnel server address"));
    }
    let port = match port {
        Some(port) => port
            .parse::<u16>()
            .ok()
            .filter(|port| *port != 0)
            .ok_or_else(|| invalid("tunnel server address has an invalid port"))?,
        None => default_port.ok_or_else(|| invalid("tunnel server address is missing a port"))?,
    };
    Ok(ServerAddress {
        host: host.to_owned(),
        port,
        plaintext,
    })
}

/// Why the connect configuration could not be resolved. One text per error, shared by
/// every SDK, pointing at the Cloud UI where it helps.
#[derive(Debug, thiserror::Error)]
pub enum ConfigError {
    #[error(
        "the deployment needs a name — pass one or set {CONNECT_NAME_ENV}. Replicas of one deployment share the name; it is what you register (connect://<name>)"
    )]
    MissingName,
    #[error("invalid deployment name {0:?} — use letters, digits, '.', '_' or '-'")]
    InvalidName(String),
    #[error("no Restate Cloud connect key — set {CONNECT_KEY_ENV} (create one at {CONNECT_KEY_URL}) or pass a key")]
    MissingKey,
    #[error("{what} {error} — copy it again from {CONNECT_KEY_URL}")]
    Key {
        what: &'static str,
        #[source]
        error: KeyError,
    },
    #[error(
        "{what} carries no API key and no token is configured: pass one, set {AUTH_TOKEN_ENV} or a file in {INPROC_AUTH_TOKEN_FILE_ENV}"
    )]
    MissingToken { what: &'static str },
    #[error("{0} is required alongside {INPROC_ENVIRONMENT_ID_ENV} (or set {CONNECT_KEY_ENV} from {CONNECT_KEY_URL})")]
    IncompleteOperatorConfig(&'static str),
    #[error("invalid {var}: {reason}")]
    InvalidOperatorConfig {
        var: &'static str,
        reason: &'static str,
    },
    #[error("{0} contains characters that cannot travel in an HTTP header (whitespace or non-printable)")]
    InvalidHeaderValue(&'static str),
    #[error("invalid tunnel servers: {0}")]
    Servers(String),
    #[error(transparent)]
    Token(#[from] TokenError),
    #[error("environment variable {0} is not valid UTF-8")]
    NonUnicodeEnvironment(&'static str),
}

/// Token loading errors never contain the token value.
#[derive(Debug, thiserror::Error)]
pub enum TokenError {
    #[error("cannot inspect auth token file {path:?}: {source}")]
    Metadata {
        path: PathBuf,
        #[source]
        source: io::Error,
    },
    #[error("auth token file {0:?} is not a regular file")]
    NotRegularFile(PathBuf),
    #[error("auth token file {path:?} is too large ({size} bytes; maximum is 65536)")]
    TooLarge { path: PathBuf, size: u64 },
    #[error("cannot open auth token file {path:?}: {source}")]
    Open {
        path: PathBuf,
        #[source]
        source: io::Error,
    },
    #[error("cannot read auth token file {path:?}: {source}")]
    Read {
        path: PathBuf,
        #[source]
        source: io::Error,
    },
    #[error("auth token file {0:?} is not valid UTF-8")]
    InvalidUtf8(PathBuf),
    #[error("auth token file {0:?} is empty after trimming")]
    Empty(PathBuf),
    #[error("auth token file {0:?} contains characters that cannot travel in an HTTP header")]
    InvalidHeader(PathBuf),
}

